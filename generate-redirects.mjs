#!/usr/bin/env node
/**
 * Generate a Cloudflare _redirects file that maps legacy Obsidian Publish URLs
 * to the Quartz kebab-case equivalents.
 *
 * Run after `npx quartz build` and before `npx wrangler deploy`.
 *
 * Example redirects:
 *   /General%20ML/Decision%20Tree        /General-ML/Decision-Tree        301
 *   /Metrics%20and%20losses/f1%20score   /Metrics-and-losses/f1-score     301
 *
 * Also redirects all legacy /Papers/* URLs to the blog's paper review tag,
 * since the Papers folder was removed in favour of inline blog links.
 */

import fs from "node:fs"
import path from "node:path"

const CONTENT_DIR = "./content"
const OUTPUT = "./public/_redirects"

// Files to skip (match quartz.config.ts ignorePatterns)
const EXCLUDE_FILES = new Set([
  "README.md",
  "claude.md",
  "ideas_1.md",
  "improvement_plan.md",
  "missing_notes.md",
])
const EXCLUDE_DIRS = new Set([
  ".obsidian",
  ".smart-connections",
  ".claude",
  ".idea",
  ".git",
  ".githooks",
  ".github",
  "CV",
  "images",
  "private",
  "templates",
])

/** Mirror of Quartz's sluggify (quartz/util/path.ts). */
function sluggifyPath(fp) {
  return fp
    .split("/")
    .map((segment) =>
      segment
        .replace(/\s/g, "-")
        .replace(/&/g, "-and-")
        .replace(/%/g, "-percent")
        .replace(/\?/g, "")
        .replace(/#/g, ""),
    )
    .join("/")
    .replace(/\/$/, "")
}

function walk(dir, relBase = "") {
  const out = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (EXCLUDE_DIRS.has(entry.name)) continue
    const rel = relBase ? `${relBase}/${entry.name}` : entry.name
    const abs = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      out.push(...walk(abs, rel))
    } else if (entry.name.endsWith(".md") && !EXCLUDE_FILES.has(entry.name)) {
      out.push(rel.replace(/\.md$/, ""))
    }
  }
  return out
}

function encodePath(p) {
  return "/" + p.split("/").map(encodeURIComponent).join("/")
}

const files = walk(CONTENT_DIR)
const lines = []

lines.push("# Legacy Obsidian Publish URL redirects")
lines.push("# Auto-generated by generate-redirects.mjs at build time")
lines.push("")

// Per-note redirects (only for notes whose slug differs from the raw path)
let noteCount = 0
for (const rel of files) {
  const newSlug = sluggifyPath(rel)
  if (rel === newSlug) continue // no transformation needed

  const oldEncoded = encodePath(rel)
  const oldDecoded = "/" + rel
  const newPath = "/" + newSlug

  lines.push(`${oldEncoded} ${newPath} 301`)
  if (oldEncoded !== oldDecoded) {
    lines.push(`${oldDecoded} ${newPath} 301`)
  }
  noteCount++
}

// Old index (capital I) → home page
lines.push("")
lines.push("# Home page (Obsidian Publish used capital I)")
lines.push("/Index / 301")

// Papers folder was removed — redirect all legacy Papers URLs to the blog
lines.push("")
lines.push("# Papers folder removed; redirect to blog paper reviews")
lines.push("/Papers/* https://andlukyane.com/tag/paperreview 301")

fs.writeFileSync(OUTPUT, lines.join("\n") + "\n")
console.log(
  `[generate-redirects] Wrote ${OUTPUT} (${noteCount} per-note redirects + Index + Papers catch-all)`,
)
