#!/usr/bin/env node
/**
 * Generate a JS redirect map (src/redirects-map.js) that maps legacy
 * Obsidian Publish URLs to the Quartz kebab-case equivalents.
 *
 * The map is consumed by src/worker.js at request time — Cloudflare
 * Workers Assets does NOT honour classic _redirects files, so redirects
 * have to be handled by a Worker script running before the ASSETS
 * binding.
 *
 * Run after `npx quartz build` and before `npx wrangler deploy`.
 *
 * Example entries:
 *   "/General%20ML/Decision%20Tree": "/General-ML/Decision-Tree"
 *   "/Metrics%20and%20losses/f1%20score": "/Metrics-and-losses/f1-score"
 *
 * The /Papers/* catch-all is handled directly in src/worker.js, not here.
 */

import fs from "node:fs"
import path from "node:path"

const CONTENT_DIR = "./content"
const OUTPUT = "./src/redirects-map.js"

// Files to skip (match quartz.config.ts ignorePatterns)
const EXCLUDE_FILES = new Set([
  "README.md",
  "claude.md",
  "ideas_1.md",
  "improvement_plan.md",
  "missing_notes.md",
])
const EXCLUDE_DIRS = new Set([
  ".obsidian",
  ".smart-connections",
  ".claude",
  ".idea",
  ".git",
  ".githooks",
  ".github",
  "CV",
  "images",
  "private",
  "templates",
])

/** Mirror of Quartz's sluggify (quartz/util/path.ts). */
function sluggifyPath(fp) {
  return fp
    .split("/")
    .map((segment) =>
      segment
        .replace(/\s/g, "-")
        .replace(/&/g, "-and-")
        .replace(/%/g, "-percent")
        .replace(/\?/g, "")
        .replace(/#/g, ""),
    )
    .join("/")
    .replace(/\/$/, "")
}

function walk(dir, relBase = "") {
  const out = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (EXCLUDE_DIRS.has(entry.name)) continue
    const rel = relBase ? `${relBase}/${entry.name}` : entry.name
    const abs = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      out.push(...walk(abs, rel))
    } else if (entry.name.endsWith(".md") && !EXCLUDE_FILES.has(entry.name)) {
      out.push(rel.replace(/\.md$/, ""))
    }
  }
  return out
}

function encodePath(p) {
  return "/" + p.split("/").map(encodeURIComponent).join("/")
}

const files = walk(CONTENT_DIR)
const entries = []

for (const rel of files) {
  const newSlug = sluggifyPath(rel)
  if (rel === newSlug) continue // no transformation needed

  const oldEncoded = encodePath(rel)
  const oldDecoded = "/" + rel
  const newPath = "/" + newSlug

  entries.push([oldEncoded, newPath])
  if (oldEncoded !== oldDecoded) {
    entries.push([oldDecoded, newPath])
  }
}

// Home page (Obsidian Publish used capital I)
entries.push(["/Index", "/"])

// Tag-page redirects from the April 2026 tag taxonomy refactor.
// The DSWoK content vault renamed `unsupervised-learning -> unsupervised`
// and `computer-vision -> cv`. Cover both with and without trailing slash
// since Quartz emits tag pages as `tags/<slug>/index.html`.
const RENAMED_TAGS = [
  ["unsupervised-learning", "unsupervised"],
  ["computer-vision", "cv"],
]
for (const [oldSlug, newSlug] of RENAMED_TAGS) {
  entries.push([`/tags/${oldSlug}`, `/tags/${newSlug}`])
  entries.push([`/tags/${oldSlug}/`, `/tags/${newSlug}/`])
}

const lines = [
  "// Auto-generated by ../generate-redirects.mjs at build time. Do not edit.",
  "// Maps legacy Obsidian Publish URLs to the Quartz kebab-case equivalents.",
  "// Consumed by ./worker.js.",
  "",
  "export default {",
]
for (const [from, to] of entries) {
  lines.push(`  ${JSON.stringify(from)}: ${JSON.stringify(to)},`)
}
lines.push("}")

fs.writeFileSync(OUTPUT, lines.join("\n") + "\n")
console.log(
  `[generate-redirects] Wrote ${OUTPUT} (${entries.length} entries)`,
)
